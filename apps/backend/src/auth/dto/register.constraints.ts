/**
 * 注册请求的契约常量——校验装饰器与 Swagger `pattern` 共用的**唯一定义处**。
 *
 * 单独成文件的理由与 `common/pagination/cursor.ts`、`pagination.constants.ts` 相同：
 * 这两份正则会经 `@ApiProperty` 的 `pattern` 选项进入 openapi.json 与前端契约，
 * 放在 DTO 里会让文档生成测试反向 import DTO；两侧都只依赖这里，改一处不会漂移。
 */

/** 用户名字符集：仅字母数字下划线连字符（含首尾空白者不匹配，直接 400） */
export const USERNAME_PATTERN = /^[a-zA-Z0-9_-]+$/;

/**
 * 密码复杂度：需同时含大写、小写、数字与**至少一个非字母数字且非空白的字符**。
 *
 * 「特殊字符」按 `[^a-zA-Z0-9\s]` 判定而不是符号白名单：白名单此前只认
 * `!@#$%^&*(),.?":{}|<>`，`_`/`-`/`+`/`~` 等常用符号被漏在外面，`Str0ng-Pass`
 * 会被 400 且报错文案说「需包含特殊字符」，用户明明已经带了——那是漏写，不是有意的收紧。
 *
 * 空白必须显式排除（`\s`）：放开成裸 `[^a-zA-Z0-9]` 时，空格/制表符/换行都能充当
 * 「特殊字符」，`Str0ng Pass` 这类密码随之可入库——而空格在界面上不可见，客户端与
 * 密码管理器又常自行 trim，用户会陷入「密码明明对却登不进去」且无法复现的境地。
 */
export const PASSWORD_PATTERN =
  /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[^a-zA-Z0-9\s])/;
