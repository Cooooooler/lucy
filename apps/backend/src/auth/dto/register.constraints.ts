/**
 * 注册请求的契约常量——校验装饰器与 Swagger `pattern` 共用的**唯一定义处**。
 *
 * 单独成文件的理由与 `common/pagination/cursor.ts`、`pagination.constants.ts` 相同：
 * 这两份正则会经 `@ApiProperty` 的 `pattern` 选项进入 openapi.json 与前端契约，
 * 放在 DTO 里会让文档生成测试反向 import DTO；两侧都只依赖这里，改一处不会漂移。
 */

/** 用户名字符集：仅字母数字下划线连字符（无前瞻，可安全下发给任意正则引擎） */
export const USERNAME_PATTERN = /^[a-zA-Z0-9_-]+$/;

/**
 * 密码复杂度：需含大写、小写、数字，以及**至少一个符号/标点**。
 *
 * 「特殊字符」判据是「非字母、非数字、非控制/格式、非分隔符」（`[^\p{L}\p{N}\p{C}\p{Z}]`），
 * 逐个绕开三类曾出问题的情况：
 * - 符号白名单（`!@#$…`）漏掉 `_`/`-`/`+`/`~` 等常用符号，`Str0ng-Pass` 会被 400
 *   且报错说「需包含特殊字符」，用户明明带了；
 * - 裸 `[^a-zA-Z0-9]` 又让空格、制表符、换行、零宽空格（U+200B）、BOM 充当特殊字符——
 *   这些字符在界面上不可见，等于「看不见的密码要求」；
 * - `[^a-zA-Z0-9\s]` 仍放过汉字等 `\p{L}` 字母（`密码密码Aa1` 可过）。
 *
 * 首尾不接受空白（`\S…\S`）：**刻意不用 `@Transform(trim)`**——trim 会静默把用户输入
 * 换成另一个字符串，而旧版正则没有 `$` 锚定、曾放行过含首尾空白的密码（` Pass1! `），
 * 一旦登录侧也 trim，那些已入库的**存量账号将永远 401 且本仓库没有改密入口**。
 * 改为在注册入口直接拒绝，既保证新密码形态明确，也不动存量凭据。
 *
 * 前瞻一律用 `[\s\S]*` 而不是 `.*`：JS 的 `.` 不匹配换行终止符，密码内部的换行会把
 * 串切成两段，位于换行之后的符号/大写/小写/数字都看不见——`Aa1\nPass!` 明明带了 `!`
 * 却会被拒，并提示「需包含符号」，用户无法理解。`[\s\S]` 跨行安全。
 */
export const PASSWORD_PATTERN =
  /^(?=[\s\S]*[a-z])(?=[\s\S]*[A-Z])(?=[\s\S]*\d)(?=[\s\S]*[^\p{L}\p{N}\p{C}\p{Z}])\S(?:[\s\S]*\S)?$/u;
